"""Sphinx configuration for the Terreate documentation (#361).

Prose is Markdown (MyST). The API reference is generated by Doxygen (#360) and
reached from here through breathe (the XML); the full Doxygen HTML is built beside it.
CMake passes the Doxygen XML directory through the environment.
"""
import os

project = "Terreate"
author = "Terreate contributors"
copyright = "Terreate contributors"
release = os.environ.get("TERREATE_VERSION", "0.1.0")

extensions = ["myst_parser", "breathe"]
source_suffix = {".md": "markdown"}
root_doc = "index"
exclude_patterns = [
    "_build",
    "mainpage.md",  # the Doxygen main page, not a Sphinx page
    "Doxyfile.in",
    "CMakeLists.txt",
]

# Existing pages link to heading anchors; resolve them and fail on a broken one.
myst_heading_anchors = 4
# The API pages are rendered from Doxygen XML. Doxygen has already resolved (and, in
# docs.doxygen, failed on) every \ref, so its labels are not re-checked here, and the
# Vulkan-Hpp types (`vk::...`) that appear in signatures live outside this project.
# This also silences any unresolved C++ cross-reference or duplicate declaration on the
# API pages, and a `{ref}` or `{cpp:...}` role in a prose page: prose uses Markdown links,
# whose broken targets are a different category (myst.*) and stay checked.
# Each doxygenfile directive of the Core page re-declares the namespace `terreate`; that
# one duplicate is expected (and the pages hold no hand-written C++ declarations).
suppress_warnings = ["ref.ref", "ref.identifier", "duplicate_declaration.cpp"]
nitpicky = True

html_theme = "furo"
html_title = "Terreate"

xml_dir = os.environ.get("TERREATE_DOXYGEN_XML", "")
breathe_projects = {"terreate": xml_dir}
breathe_default_project = "terreate"
breathe_domain_by_extension = {"hpp": "cpp"}
